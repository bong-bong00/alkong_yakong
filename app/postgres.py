"""Bound-parameter SQL adapter; each service has an isolated schema in one DB."""
from __future__ import annotations
import os
import re
import sqlite3
from urllib.parse import urlsplit

SCHEMAS = {"main": "alkong_main", "medication": "alkong_medication"}
QUOTED = re.compile(r"('(?:''|[^'])*'|\"(?:\"\"|[^\"])*\"|--[^\n]*|/\*.*?\*/)", re.S)


def schema_for_role(role=None):
    role = (role or os.getenv("SERVICE_ROLE", "")).strip().lower()
    if role not in SCHEMAS:
        raise ValueError("PostgreSQL requires SERVICE_ROLE=main or medication")
    return SCHEMAS[role]


def validate_url(url):
    try:
        parsed = urlsplit(url)
        if parsed.scheme not in {"postgres", "postgresql"} or not parsed.hostname or not parsed.path.strip("/"):
            raise ValueError()
    except (ValueError, TypeError):
        raise ValueError("NEON_DATABASE_URL must be a PostgreSQL connection URL") from None


def translate_sql(statement):
    """Translate application syntax, never interpolate user values."""
    statement = statement.strip().rstrip(";")
    ignore = bool(re.match(r"INSERT\s+OR\s+IGNORE\b", statement, re.I))
    if re.match(r"INSERT\s+OR\s+REPLACE\b", statement, re.I):
        raise sqlite3.OperationalError("PostgreSQL requires explicit ON CONFLICT updates")
    parts = QUOTED.split(statement)
    for i in range(0, len(parts), 2):
        code = re.sub(r"\bINSERT\s+OR\s+IGNORE\b", "INSERT", parts[i], flags=re.I)
        code = re.sub(r"\bINTEGER\s+PRIMARY\s+KEY\s+AUTOINCREMENT\b", "BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY", code, flags=re.I)
        code = re.sub(r"\bregistration_revision\s+INTEGER(?:\s+NOT\s+NULL)?(?:\s+DEFAULT\s+1)?", "registration_revision TEXT NOT NULL DEFAULT '1'", code, flags=re.I)
        code = re.sub(r"\bREAL\b", "DOUBLE PRECISION", code, flags=re.I)
        code = re.sub(r"\bCURRENT_TIMESTAMP\b", "sqlite_timestamp()", code, flags=re.I)
        code = re.sub(r"\bdatetime\s*\(", "sqlite_datetime(", code, flags=re.I)
        parts[i] = re.sub(r"\browid\b", "_sqlite_rowid", code, flags=re.I)
    statement = "".join(parts)
    if ignore:
        statement += " ON CONFLICT DO NOTHING"
    if re.match(r"CREATE\s+TABLE\b", statement, re.I):
        at = statement.rfind(")")
        statement = statement[:at] + ", _sqlite_rowid BIGINT GENERATED BY DEFAULT AS IDENTITY" + statement[at:]
    parts = QUOTED.split(statement)
    for i in range(len(parts)):
        parts[i] = parts[i].replace("%", "%%")
        if i % 2 == 0:
            parts[i] = parts[i].replace("?", "%s")
    return "".join(parts)


class Row:
    def __init__(self, names, values):
        pairs = [(k, v) for k, v in zip(names, values) if k != "_sqlite_rowid"]
        self.names = [k for k, _ in pairs]
        self.values = tuple(v for _, v in pairs)

    def keys(self):
        return self.names

    def __getitem__(self, key):
        if isinstance(key, (int, slice)):
            return self.values[key]
        for i, name in enumerate(self.names):
            if name.casefold() == str(key).casefold():
                return self.values[i]
        raise IndexError(key)

    def __iter__(self):
        return iter(self.values)

    def __len__(self):
        return len(self.values)


class Cursor:
    def __init__(self, connection):
        self.connection = connection
        self.raw = connection.raw.cursor()
        self.lastrowid = None
        self.rowcount = -1

    @property
    def description(self):
        return [(c.name, c.type_code, None, None, None, None, None) for c in self.raw.description
                if c.name != "_sqlite_rowid"] if self.raw.description else None

    def execute(self, statement, parameters=()):
        import psycopg
        self.lastrowid = None
        meta = re.fullmatch(r"\s*PRAGMA table_info\((\w+)\)\s*;?", statement, re.I)
        if meta:
            statement = """SELECT ordinal_position-1 AS cid, column_name AS name, data_type AS type,
                CASE WHEN is_nullable='NO' THEN 1 ELSE 0 END AS \"notnull\", column_default AS dflt_value,
                0 AS pk FROM information_schema.columns WHERE table_schema=? AND table_name=?
                AND column_name <> '_sqlite_rowid' ORDER BY ordinal_position"""
            parameters = (self.connection.schema, meta[1])
        elif "sqlite_master" in statement:
            if statement.strip() != "SELECT name FROM sqlite_master WHERE type='table'":
                raise sqlite3.OperationalError("Unsupported SQLite metadata query")
            statement = "SELECT table_name AS name FROM information_schema.tables WHERE table_schema=?"
            parameters = (self.connection.schema,)
        elif statement.strip().upper() == "PRAGMA FOREIGN_KEYS = ON":
            return self
        elif statement.strip().upper() in {"BEGIN", "BEGIN IMMEDIATE"}:
            self.connection.raw.execute("BEGIN")
            self.connection.ensure_search_path()
            if statement.strip().upper() == "BEGIN IMMEDIATE":
                self.connection.raw.execute("SELECT pg_advisory_xact_lock(hashtext(%s))", (self.connection.schema,))
            return self
        translated = translate_sql(statement)
        inserted = re.match(r"INSERT\s+INTO\s+(\w+)\b", translated, re.I)
        if inserted and "RETURNING" not in translated.upper():
            from init_db import TABLE_DEFINITIONS
            definition = TABLE_DEFINITIONS.get(inserted[1], "")
            key = "id" if re.search(r"\bid\s+(?:TEXT|INTEGER)\s+PRIMARY", definition, re.I) else "_sqlite_rowid"
            translated += f" RETURNING {key}"
        self.connection.ensure_search_path()
        self.connection.raw.execute("SAVEPOINT alkong_statement")
        try:
            self.raw.execute(translated, tuple(parameters))
            self.rowcount = self.raw.rowcount
            if inserted:
                row = self.raw.fetchone()
                self.lastrowid = row[0] if row else None
            self.connection.raw.execute("RELEASE SAVEPOINT alkong_statement")
            return self
        except psycopg.Error as error:
            self.connection.raw.execute("ROLLBACK TO SAVEPOINT alkong_statement")
            self.connection.raw.execute("RELEASE SAVEPOINT alkong_statement")
            kind = sqlite3.IntegrityError if isinstance(error, psycopg.IntegrityError) else sqlite3.OperationalError
            raise kind("PostgreSQL statement failed (" + str(error.sqlstate or "unknown") + ")") from None

    def _row(self, value):
        return None if value is None else Row([c.name for c in self.raw.description], value)

    def fetchone(self):
        return self._row(self.raw.fetchone())

    def fetchall(self):
        return [self._row(value) for value in self.raw.fetchall()]

    def __iter__(self):
        return iter(self.fetchall())

    def executemany(self, statement, parameters):
        count = 0
        for values in parameters:
            self.execute(statement, values)
            count += max(0, self.rowcount)
        self.rowcount = count
        return self


class Connection:
    def __init__(self, url, schema):
        import certifi
        import psycopg
        validate_url(url)
        self.validate_schema(schema)
        self.schema = schema
        settings = {"sslmode": "verify-full", "sslrootcert": certifi.where()}
        if urlsplit(url).hostname in {"localhost", "127.0.0.1", "::1"}:
            settings = {"sslmode": "disable"}
        try:
            self.raw = psycopg.connect(url, cursor_factory=psycopg.ClientCursor, connect_timeout=10, **settings)
            self._transaction_schema = None
            self.set_schema(schema)
            self.raw.commit()
        except psycopg.Error:
            if hasattr(self, 'raw'):
                self.raw.close()
            raise sqlite3.OperationalError("PostgreSQL connection unavailable") from None

    @staticmethod
    def validate_schema(schema):
        if schema not in SCHEMAS.values() and not re.fullmatch(r"alkong_test_[a-f0-9]{16,32}", schema):
            raise ValueError("Unsupported database schema")

    def set_schema(self, schema):
        from psycopg import sql
        self.validate_schema(schema)
        # Transaction-local settings also work through Neon's transaction pooler.
        self.raw.execute(sql.SQL("SET LOCAL search_path TO {}, pg_catalog").format(sql.Identifier(schema)))
        self.raw.execute("SET LOCAL TIME ZONE 'UTC'")
        self.schema = schema
        self._transaction_schema = schema

    def ensure_search_path(self):
        from psycopg.pq import TransactionStatus
        if self.raw.info.transaction_status == TransactionStatus.IDLE or self._transaction_schema != self.schema:
            self.set_schema(self.schema)

    def cursor(self):
        return Cursor(self)

    def execute(self, statement, parameters=()):
        return self.cursor().execute(statement, parameters)

    def executemany(self, statement, parameters):
        return self.cursor().executemany(statement, parameters)

    def commit(self):
        self.raw.commit()
        self._transaction_schema = None

    def rollback(self):
        self.raw.rollback()
        self._transaction_schema = None

    def close(self):
        self.raw.close()

    def __enter__(self):
        return self

    def __exit__(self, kind, value, traceback):
        try:
            self.rollback() if kind else self.commit()
        finally:
            self.close()


def prepare_schema(connection):
    """DDL only; no automatic user/demo data or explanation seeds."""
    from psycopg import sql
    from init_db import TABLE_DEFINITIONS, INDEXES, ensure_additive_columns
    connection.raw.execute(sql.SQL("CREATE SCHEMA IF NOT EXISTS {}").format(sql.Identifier(connection.schema)))
    connection.set_schema(connection.schema)
    connection.raw.execute("""CREATE OR REPLACE FUNCTION sqlite_timestamp() RETURNS text LANGUAGE sql
        STABLE AS $$ SELECT to_char(CURRENT_TIMESTAMP AT TIME ZONE 'UTC', 'YYYY-MM-DD\"T\"HH24:MI:SS') $$""")
    connection.raw.execute("""CREATE OR REPLACE FUNCTION sqlite_datetime(value text, modifier text DEFAULT NULL)
        RETURNS timestamptz LANGUAGE plpgsql STABLE AS $$
        BEGIN
          RETURN (CASE WHEN value='now' THEN CURRENT_TIMESTAMP ELSE value::timestamptz END)
                 + COALESCE(modifier::interval, interval '0 seconds');
        EXCEPTION WHEN invalid_datetime_format OR datetime_field_overflow THEN RETURN NULL;
        END $$""")
    for name, definition in TABLE_DEFINITIONS.items():
        connection.execute(definition.replace(f"CREATE TABLE {name}", f"CREATE TABLE IF NOT EXISTS {name}"))
    ensure_additive_columns(connection.cursor())
    for statement in INDEXES:
        connection.execute(statement)
